// Appends the retired-snapshot redirects to .vitepress/dist/_redirects after
// `vitepress build` has copied docs/public/_redirects there.
//
// Why generated: the alpha snapshot is served at /v<next>-SNAPSHOT/ (and
// /zh/v<next>-SNAPSHOT/), and its label follows the framework's pom.xml
// (scripts/inject-alpha.mjs). Each release retires a label whose URLs people
// have pasted into issues and chats. Cloudflare Pages' _redirects has no
// regular expressions, so a single generic rule is not possible; a
// hand-written rule per label would be one more place to forget at release.
// Instead, every version this site has released (versionsConfig.current plus
// each docs/archive/v* tree) from FIRST_SERVED_SNAPSHOT on gets its former
// snapshot URLs redirected to the latest docs. The live snapshot label is
// never a released version, so it can never be redirected away.
//
// FIRST_SERVED_SNAPSHOT is a historical fact, not a moving version: 6.3.0 was
// the first label the alpha injection ever published. Earlier releases never
// had snapshot URLs, and skipping them keeps the dynamic-rule count low
// (Cloudflare Pages allows 100 dynamic redirects; this adds 3 per release).
//
// Fail-closed: no dist/_redirects (the build did not run or did not copy
// docs/public), an unparseable versionsConfig.current, or an unreadable
// docs/archive exits non-zero. Rerunning is idempotent: an earlier generated
// section is replaced, not duplicated.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const FIRST_SERVED_SNAPSHOT = '6.3.0';
const DIST_REDIRECTS = path.join('.vitepress', 'dist', '_redirects');
const BEGIN = '# BEGIN generated by scripts/generate-redirects.mjs: retired alpha snapshot labels';
const END = '# END generated by scripts/generate-redirects.mjs';

function fail(reason) {
  console.error(`generate-redirects: ${reason}`);
  process.exit(1);
}

function compareSemver(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i += 1) {
    if (pa[i] !== pb[i]) return pa[i] - pb[i];
  }
  return 0;
}

if (!existsSync(DIST_REDIRECTS)) {
  fail(`${DIST_REDIRECTS} not found; run vitepress build first (it copies docs/public/_redirects)`);
}

const config = readFileSync(path.join('.vitepress', 'config.mts'), 'utf-8');
const current = [...config.matchAll(/^\s*current:\s*['"]v(\d+\.\d+\.\d+)['"]/gm)];
if (current.length !== 1) {
  fail(`expected exactly one versionsConfig "current:" key in .vitepress/config.mts, found ${current.length}`);
}

const released = new Set([current[0][1]]);
for (const entry of readdirSync(path.join('docs', 'archive'), { withFileTypes: true })) {
  const m = /^v(\d+\.\d+\.\d+)$/.exec(entry.name);
  if (entry.isDirectory() && m) released.add(m[1]);
}

// The snapshot tree this build actually rendered is never retired, whatever
// the version sources say. generate-snapshot-sidebar.mjs already refuses a
// label that is not newer than the current release; this is the second guard.
const built = new Set();
for (const dir of [path.join('.vitepress', 'dist'), path.join('.vitepress', 'dist', 'zh')]) {
  if (!existsSync(dir)) continue;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const m = /^v(\d+\.\d+\.\d+)-SNAPSHOT$/.exec(entry.name);
    if (entry.isDirectory() && m) built.add(m[1]);
  }
}

const versions = [...released]
  .filter((v) => compareSemver(v, FIRST_SERVED_SNAPSHOT) >= 0)
  .filter((v) => !built.has(v))
  .sort(compareSemver);
if (versions.length === 0) {
  fail(`no released version at or after ${FIRST_SERVED_SNAPSHOT} found; the version sources are not what this script expects`);
}

const lines = [BEGIN];
for (const v of versions) {
  const label = `v${v}-SNAPSHOT`;
  // Most specific first: Cloudflare Pages applies the first matching rule.
  lines.push(
    `/${label}/zh/* /zh/:splat 301`,
    `/zh/${label}/* /zh/:splat 301`,
    `/zh/${label} /zh/ 301`,
    `/${label}/* /:splat 301`,
    `/${label} / 301`,
  );
}
lines.push(END);

const existing = readFileSync(DIST_REDIRECTS, 'utf-8');
const begin = existing.indexOf(BEGIN);
const base = begin === -1 ? existing : existing.slice(0, begin);
writeFileSync(DIST_REDIRECTS, `${base.replace(/\n*$/, '\n\n')}${lines.join('\n')}\n`);

console.log(`generate-redirects: ${DIST_REDIRECTS} += retired snapshot labels ${versions.map((v) => `v${v}-SNAPSHOT`).join(', ')}`);
