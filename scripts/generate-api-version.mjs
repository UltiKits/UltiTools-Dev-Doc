// Reads <ultitools.version> from examples/pom.xml and the directory listing
// of docs/archive/, then writes both — together with a build-time UTC
// timestamp — into functions/api/_shared/version.generated.js.
//
// Why this matters: functions/api/[[path]].js needs a version number at request
// time to build the /api/{version}/{rest} -> javadoc.io upstream URL, and (as
// of Phase 2, D-29) the set of archived versions to decide whether a
// version-aware backlink should carry a version prefix or fall back to
// latest. Pages Functions have no access to examples/pom.xml or docs/archive/
// at runtime — only whatever the Build command produced before Cloudflare
// packaged functions/. This script is that Build command step (see
// package.json's "build" script).
//
// Fail-closed on purpose, for both reads: if examples/pom.xml can't be parsed
// OR docs/archive can't be read, exit non-zero and let the whole Pages build
// fail rather than ship a Function that silently has no version to serve, or
// silently treats every version as unarchived. Same reasoning as
// scripts/check-version-consistency.sh's three-way equality check — for the
// docs/archive read specifically, readdirSync's own exception is left
// unhandled (no try/catch) so it propagates and kills the build the same way
// the <ultitools.version> parse failure below does with its explicit
// process.exit(1).
//
// The generated file is gitignored, not committed (see .gitignore's
// functions/api/_shared/version.generated.js entry and
// 01-01-SUMMARY.md for the full reasoning): a committed copy would be
// byte-identical to a stale build and would silently mask a failed
// build-time injection (Cloudflare Pages' "Build command" not running
// before functions/ is packaged) instead of failing closed. This comment
// previously said the opposite (that the file was committed) — that was
// wrong even at the time it was written; .gitignore already excluded this
// path, and `git ls-tree` on `master` confirms the file has never actually
// been tracked.
//
// ARCHIVED_VERSIONS excludes any directory name ending in "-SNAPSHOT"
// (03-02-PLAN.md, Claude's Discretion, 03-RESEARCH.md's "ARCHIVED_VERSIONS
// 顺序耦合的最终建议"). `npm run build:with-alpha` runs
// scripts/inject-alpha.mjs before `npm run build`, so docs/archive/ already
// contains v6.3.0-SNAPSHOT by the time this script's readdirSync runs here
// — that ordering is structurally forced (@viteplus/versions can only
// discover a version directory that already exists on disk), so without
// this filter SNAPSHOT would silently join the array as a side effect of
// script-call order rather than as a decision anyone could read in code.
// The exclusion itself is semantic, not just order-hygiene: this array
// means "versions with a real javadoc.io index" (functions/api/_shared/
// backlink.js's strict-equality match, Phase 2 D-29), and v6.3.0-SNAPSHOT
// has never been published to Maven Central, so it has no javadoc.io index
// to link to. Matching on a "-SNAPSHOT" suffix rather than the literal
// "v6.3.0-SNAPSHOT" string means a future snapshot version's directory name
// doesn't require a matching edit here.

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';

const POM_PATH = 'examples/pom.xml';
const ARCHIVE_DIR = 'docs/archive';
const OUTPUT_PATH = 'functions/api/_shared/version.generated.js';

const pom = readFileSync(POM_PATH, 'utf-8');
const match = pom.match(/<ultitools\.version>([^<]+)<\/ultitools\.version>/);

if (!match) {
  console.error(
    `generate-api-version: could not parse <ultitools.version> from ${POM_PATH}`
  );
  process.exit(1);
}

const CURRENT_VERSION = match[1].trim();
const GENERATED_AT = new Date().toISOString();

// Fail-closed: readdirSync throwing (e.g. docs/archive missing) is left
// uncaught, propagating out of this module and failing the whole build —
// same posture as the <ultitools.version> parse failure above, not a
// silently-empty ARCHIVED_VERSIONS array.
const ARCHIVED_VERSIONS = readdirSync(ARCHIVE_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => !name.endsWith('-SNAPSHOT'))
  .sort();

mkdirSync('functions/api/_shared', { recursive: true });

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/generate-api-version.mjs at build time. Do not edit by hand.
export const CURRENT_VERSION = ${JSON.stringify(CURRENT_VERSION)};
export const GENERATED_AT = ${JSON.stringify(GENERATED_AT)};
export const ARCHIVED_VERSIONS = ${JSON.stringify(ARCHIVED_VERSIONS)};
`
);

console.log(
  `generate-api-version: wrote ${OUTPUT_PATH} (${CURRENT_VERSION}, ${GENERATED_AT}, ${ARCHIVED_VERSIONS.length} archived versions)`
);
