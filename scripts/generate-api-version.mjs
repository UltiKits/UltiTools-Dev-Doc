// Reads <ultitools.version> from examples/pom.xml and writes it, together with
// a build-time UTC timestamp, into functions/api/_shared/version.generated.js.
//
// Why this matters: functions/api/[[path]].js needs a version number at request
// time to build the /api/{version}/{rest} -> javadoc.io upstream URL, but Pages
// Functions have no access to examples/pom.xml at runtime — only whatever the
// Build command produced before Cloudflare packaged functions/. This script is
// that Build command step (see package.json's "build" script).
//
// Fail-closed on purpose: if examples/pom.xml can't be parsed, exit non-zero
// and let the whole Pages build fail rather than ship a Function that silently
// has no version to serve. Same reasoning as scripts/check-version-consistency.sh's
// three-way equality check.
//
// The generated file IS committed to git, not gitignored. Reason: if Assumption
// A1 (Build command finishes before Cloudflare scans functions/) turns out to be
// false, the Function still imports a usable — if stale — committed value instead
// of failing to import at all. A failed import takes down the whole preview
// deployment, which is the one thing every other observation in this Phase
// depends on. A stale x-version-generated-at header is a diagnosable outcome;
// a broken preview is not. The committed value doubles as the RESEARCH.md
// §Alternatives fallback (Dashboard environment variable) in a form that needs
// zero manual Dashboard steps to already exist.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const POM_PATH = 'examples/pom.xml';
const OUTPUT_PATH = 'functions/api/_shared/version.generated.js';

const pom = readFileSync(POM_PATH, 'utf-8');
const match = pom.match(/<ultitools\.version>([^<]+)<\/ultitools\.version>/);

if (!match) {
  console.error(
    `generate-api-version: could not parse <ultitools.version> from ${POM_PATH}`
  );
  process.exit(1);
}

const CURRENT_VERSION = match[1].trim();
const GENERATED_AT = new Date().toISOString();

mkdirSync('functions/api/_shared', { recursive: true });

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/generate-api-version.mjs at build time. Do not edit by hand.
export const CURRENT_VERSION = ${JSON.stringify(CURRENT_VERSION)};
export const GENERATED_AT = ${JSON.stringify(GENERATED_AT)};
`
);

console.log(`generate-api-version: wrote ${OUTPUT_PATH} (${CURRENT_VERSION}, ${GENERATED_AT})`);
